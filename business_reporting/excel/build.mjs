import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {Workbook, SpreadsheetFile} from '@oai/artifact-tool';
const root=process.argv[2];
const outputDir=process.argv[3];
if(!root || !outputDir) throw new Error('Usage: node build.mjs <absolute-repository-root> <absolute-output-directory>');
await fs.mkdir(outputDir,{recursive:true});
const csv=await fs.readFile(`${root}/raw/KAG_conversion_data.csv`,'utf8');
const wb=Workbook.create();
const summary=wb.worksheets.add('Campaigns');
const ads=wb.worksheets.add('Ads');
// Fixed source has no quoted delimiters; the source is independently parsed by csv.DictReader.
const lines=csv.trim().split(/\r?\n/).map(x=>x.split(','));
const numeric=new Set([5,6,7,8,9,10]);
const data=lines.map((r,i)=>r.map((v,c)=>i>0&&numeric.has(c)?Number(v):v));
const n=data.length;
ads.getRange(`A1:K${n}`).values=data;
ads.tables.add(`A1:K${n}`,true,'AdsTable');
ads.freezePanes.freezeRows(1);
ads.getRange(`A1:K${n}`).format.font={name:'Arial',size:10};
ads.getRange('A1:K1').format={fill:'#263B57',font:{bold:true,color:'#FFFFFF'},rowHeight:36,wrapText:true};
ads.getRange(`A1:K${n}`).format.columnWidth=18;
ads.getRange(`I2:I${n}`).setNumberFormat('#,##0.00');
ads.getRange(`F2:H${n}`).setNumberFormat('#,##0');
ads.getRange(`J2:K${n}`).setNumberFormat('#,##0');
ads.getRange('M2').values=[['Source: repository raw/KAG_conversion_data.csv; 1,143 ads.']];
ads.getRange('M3').values=[['Campaign dates and currency code are not supplied by the source.']];
ads.getRange('M4').values=[['Spend is shown in source monetary units. No revenue or budget fields.']];
summary.getRange('A1:K35').format.font={name:'Arial',size:10};
summary.getRange('A1:K35').format.rowHeight=23;
summary.getRange('A1:K35').format.columnWidth=15;
summary.getRange('A2').values=[['Campaign performance']];
summary.getRange('A2').format.font={size:16,bold:true};
summary.getRange('A3').values=[['Source snapshot. Rates use totals, not averages of ad-level ratios.']];
summary.getRange('A5:I5').values=[['Campaign','Spend','Impressions','Clicks','Approved','CPA','CTR','CPC','Spend share']];
summary.getRange('A5:I5').format={fill:'#263B57',font:{bold:true,color:'#FFFFFF'},rowHeight:28};
summary.getRange('A6:A8').values=[['916'],['936'],['1178']];
for(let r=6;r<=8;r++){
  const f=['I','G','H','K'].map(c=>`=SUMIFS(AdsTable[${data[0][c.charCodeAt(0)-65]}],AdsTable[xyz_campaign_id],A${r})`);
  summary.getRange(`B${r}:I${r}`).formulas=[[...f,`=IF(E${r}=0,"n.a.",B${r}/E${r})`,`=IF(C${r}=0,"n.a.",D${r}/C${r})`,`=IF(D${r}=0,"n.a.",B${r}/D${r})`,`=IF($B$9=0,"n.a.",B${r}/$B$9)`]];
}
summary.getRange('A9').values=[['Total']];
summary.getRange('B9:I9').formulas=[['=SUM(B6:B8)','=SUM(C6:C8)','=SUM(D6:D8)','=SUM(E6:E8)','=IF(E9=0,"n.a.",B9/E9)','=IF(C9=0,"n.a.",D9/C9)','=IF(D9=0,"n.a.",B9/D9)','=IF(B9=0,"n.a.",SUM(I6:I8))']];
summary.getRange('A9:I9').format.font.bold=true;
for(const c of ['B','F','H']) summary.getRange(`${c}6:${c}9`).setNumberFormat('#,##0.00');
summary.getRange('C6:E9').setNumberFormat('#,##0');
for(const c of ['G','I']) summary.getRange(`${c}6:${c}9`).setNumberFormat('0.00%');
summary.getRange('G6:G9').setNumberFormat('0.000%');
const chart=summary.charts.add('bar',[summary.getRange('A5:A8'),summary.getRange('F5:F8')]);
chart.title='Cost per approved conversion';
chart.hasLegend=false;
chart.setPosition('A12','F25');
chart.titleTextStyle.typeface='Arial';
chart.titleTextStyle.fontSize=12;
chart.series.items[0].fill='#426D9B';
chart.yAxis={numberFormatCode:'0.00',numberFormatSourceLinked:false};
summary.getRange('G12').values=[['Readout']];
summary.getRange('G12').format.font.bold=true;
summary.getRange('G14').values=[['CPA = spend / approved conversions.']];
summary.getRange('G16').values=[['Campaign 1178 holds most spend.']];
summary.getRange('G18').values=[['Small campaign 916 is not a scaling forecast.']];
summary.getRange('G20').values=[['No ROI or acquisition-cost claim is supported.']];
summary.getRange('A27').values=[['Ad lookup (editable ID)']];
summary.getRange('A28:D28').values=[['Ad ID','Campaign','Age band','Spend']];
summary.getRange('A28:D28').format={fill:'#263B57',font:{bold:true,color:'#FFFFFF'}};
summary.getRange('A29').values=[['708746']];
summary.getRange('A29').format.fill='#FFF2CC';
summary.getRange('B29:D29').formulas=[['=_xlfn.XLOOKUP(A29,AdsTable[ad_id],AdsTable[xyz_campaign_id],"Not found",0)','=_xlfn.XLOOKUP(A29,AdsTable[ad_id],AdsTable[age],"Not found",0)','=_xlfn.XLOOKUP(A29,AdsTable[ad_id],AdsTable[Spent],"Not found",0)']];
summary.getRange('D29').setNumberFormat('#,##0.00');
summary.getRange('A32').values=[['CTR = clicks / impressions. CPC = spend / clicks. Currency is unspecified.']];
summary.getRange('A33').values=[['VBA module creates an additional native PivotTable when run in Excel.']];
for(const sheet of [summary,ads])sheet.showGridLines=false;
// Verify recalculation on edits, then restore the original source.
const original=ads.getRange('I2').values[0][0];
const base=summary.getRange('B6').values[0][0];
ads.getRange('I2').values=[[original+10]];
assert.ok(Math.abs(summary.getRange('B6').values[0][0]-base-10)<1e-6);
ads.getRange('I2').values=[[original]];
summary.getRange('A29').values=[['missing-ad']];
assert.equal(summary.getRange('B29').values[0][0],'Not found');
summary.getRange('A29').values=[['708746']];
wb.recalculate();
const expected=JSON.parse(await fs.readFile(`${root}/business_reporting/validation.json`,'utf8'));
for(let i=0;i<3;i++){
 const r=summary.getRange(`A${i+6}:I${i+6}`).values[0];
 const e=expected.campaigns.find(x=>x.campaign===r[0]);
 assert.ok(Math.abs(r[1]-e.spend)<1e-6);
 assert.equal(r[4],e.approved);
 assert.ok(Math.abs(r[5]-e.cpa)<1e-6);
}
console.log((await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!',options:{useRegex:true,maxResults:20},summary:'Formula errors'})).ndjson);
for(const [sheetName,range,file] of [['Campaigns','A1:K34','summary.png'],['Ads','A1:K12','ads.png']]){
 const preview=await wb.render({sheetName,range,scale:1.5});
 await fs.writeFile(`${outputDir}/${file}`,new Uint8Array(await preview.arrayBuffer()));
}
const output=await SpreadsheetFile.exportXlsx(wb);
await output.save(`${outputDir}/campaign_reporting.xlsx`);
await fs.copyFile(`${outputDir}/campaign_reporting.xlsx`,`${root}/business_reporting/excel/campaign_reporting.xlsx`);
console.log('Workbook exported; campaign totals and edit recalculation verified.');
